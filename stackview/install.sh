#!/usr/bin/env bash
# stackview/install.sh -- dedicated auto-refresh stack views (separate tmux panes)
#
# 1. apt: tmux
# 2. files: ~/stackview/stackview.py + ~/stackview/stackview-pane.sh
# 3. ~/.gdbinit: `init-stackview` define (own marker block)
# 4. ~/.bashrc marker block: source /etc/bash_aliases.d/.bashrc_alias_gdb_stack
#    (alias file lives in /etc/bash_aliases.d/, copied from this folder,
#    executable; Debian bash does NOT source that dir by default -> the
#    ~/.bashrc block sources it explicitly)
#
# In gdb:   `init-stackview` (also loaded via `pwn`/`init-pwngdb`, see README)
#           -> on EVERY stop EVERY view is written to its OWN file:
#              /tmp/gdb-stackview-stack.txt  (raw stack memory from rsp)
#              /tmp/gdb-stackview-frame.txt  (current stackframe, `info frame`)
# In tmux:  ONE pane PER view:  tmux split-window -h 'bash ~/stackview/stackview-pane.sh stack'
#                                   tmux split-window -h 'bash ~/stackview/stackview-pane.sh frame'
#           or aliases:        gdb-tmux-sv-stack / gdb-tmux-sv-frame (inside tmux)
#
# default views: @stack + @frame   (gdb: `stackview` to list, `stackview <views...>` to set)
set -euo pipefail

HOME_DIR="${HOME:?}"
SRC="$(cd "$(dirname "$0")" && pwd)"
DEST="$HOME_DIR/stackview"
PASS=0; FAIL=0
log()  { printf '\n\033[1;36m[stackview]\033[0m %s\n' "$*"; }
ok()   { printf '  \033[1;32mPASS\033[0m  %s\n' "$*"; PASS=$((PASS+1)); }
bad()  { printf '  \033[1;31mFAIL\033[0m  %s\n' "$*"; FAIL=$((FAIL+1)); }
[ "$(id -u)" -eq 0 ] && SUDO="" || SUDO="sudo"

# --- shared helper: idempotent marker block in ~/.gdbinit --------------------
gdbinit_block() { # $1=name, content on stdin
    local name="$1" init="$HOME_DIR/.gdbinit"
    touch "$init"
    sed -i "/^# >>> $name >>>$/,/^# <<< $name <<</d" "$init" 2>/dev/null || true
    printf '# >>> %s >>>\n' "$name" >> "$init"
    cat >> "$init"
    printf '# <<< %s <<<\n\n' "$name" >> "$init"
}

# --- shared helper: idempotent marker block in ~/.bashrc ----------------------
bashrc_block() { # $1=name, content on stdin
    local name="$1" file="$HOME_DIR/.bashrc"
    touch "$file"
    sed -i "/^# >>> $name >>>$/,/^# <<< $name <<</d" "$file" 2>/dev/null || true
    printf '# >>> %s >>>\n' "$name" >> "$file"
    cat >> "$file"
    printf '# <<< %s <<<\n\n' "$name" >> "$file"
}

# ---------------------------------------------------------------------------
log "1/4  apt (tmux)"
export DEBIAN_FRONTEND=noninteractive
if $SUDO apt-get install -y tmux >/dev/null 2>&1; then ok "tmux present"; else bad "apt install tmux failed"; fi

# ---------------------------------------------------------------------------
log "2/4  files -> ~/stackview"
mkdir -p "$DEST"
cp "$SRC/stackview.py"       "$DEST/stackview.py"
cp "$SRC/stackview-pane.sh"  "$DEST/stackview-pane.sh"
chmod +x "$DEST/stackview-pane.sh"
[ -f "$DEST/stackview.py" ] && [ -f "$DEST/stackview-pane.sh" ] \
    && ok "stackview.py + stackview-pane.sh installed" || bad "files missing after copy"

# ---------------------------------------------------------------------------
log "3/4  ~/.gdbinit (init-stackview define)"
GDBINIT="$HOME_DIR/.gdbinit"
if [ -f "$GDBINIT" ] && ! grep -q '^# >>>' "$GDBINIT"; then
    [ -f "$HOME_DIR/.gdbinit.legacy" ] || cp "$GDBINIT" "$HOME_DIR/.gdbinit.legacy"
    grep -q '^# ~/.gdbinit -- generated by install_gdb.bash' "$GDBINIT" \
        && : > "$GDBINIT" || true   # || true: custom files (no signature) must not abort
fi
{
    echo "define init-stackview"
    echo "source ~/stackview/stackview.py"
    echo "end"
    echo "document init-stackview"
    echo "Auto stack views: every stop writes EACH view to /tmp/gdb-stackview-<view>.txt (one pane per view: bash ~/stackview/stackview-pane.sh <view>)"
    echo "end"
} | gdbinit_block stackview
grep -q 'source ~/stackview/stackview.py' "$HOME_DIR/.gdbinit" \
    && ok "init-stackview wired into ~/.gdbinit" || bad "gdbinit block missing"

# ---------------------------------------------------------------------------
log "4/4  aliases file -> /etc/bash_aliases.d/ + ~/.bashrc source block"
ALIAS_DEST=/etc/bash_aliases.d/.bashrc_alias_gdb_stack
$SUDO mkdir -p /etc/bash_aliases.d
if $SUDO cp "$SRC/.bashrc_alias_gdb_stack" "$ALIAS_DEST" \
   && $SUDO chmod +x "$ALIAS_DEST"; then
    ok "$ALIAS_DEST installed (executable)"
else
    bad "could not copy/chmod $ALIAS_DEST (need $SUDO?)"
fi
[ -x "$ALIAS_DEST" ] && ok "aliases file is executable" || bad "aliases file not executable"
{
    echo "# heap-tools: source the gdb stack-view pane aliases (gdb-tmux-sv-*)"
    echo "[ -f $ALIAS_DEST ] && . $ALIAS_DEST"
} | bashrc_block stack-tools
grep -q "\. $ALIAS_DEST" "$HOME_DIR/.bashrc" \
    && ok "~/.bashrc sources $ALIAS_DEST" || bad "source block missing from .bashrc"

# ---------------------------------------------------------------------------
log "verify"
cat > /tmp/stackview-check.c <<'CEOF'
#include <stdlib.h>
int main(void) {
    void *a = malloc(0x20);
    void *b = malloc(0x100);
    void *c = malloc(0x20);
    free(b);
    free(a);
    free(c);
    return 0;
}
CEOF
cat > /tmp/stackview-check.gdb <<'EOF2'
set pagination off
init-stackview
starti
break stackview-check.c:8
continue
quit
EOF2
gcc -g -O0 -o /tmp/stackview-check /tmp/stackview-check.c 2>/dev/null
rm -f /tmp/gdb-stackview-*.txt /tmp/gdb-stackview-req/*
timeout 150 gdb -q -batch -x /tmp/stackview-check.gdb /tmp/stackview-check >/dev/null 2>&1 || true
grep -q 'rsp' /tmp/gdb-stackview-stack.txt 2>/dev/null \
    && ok "view file gdb-stackview-stack.txt written (raw memory)" \
    || bad "stack view file not written"
grep -q 'frame at' /tmp/gdb-stackview-frame.txt 2>/dev/null \
    && ok "view file gdb-stackview-frame.txt written (current frame)" \
    || bad "frame view file not written"
rm -f /tmp/stackview-check.gdb /tmp/gdb-stackview-*.txt /tmp/stackview-check /tmp/stackview-check.c

# aliases load in an interactive shell (chain: .bashrc -> source /etc file)
AL=$(bash -ic 'alias gdb-tmux-sv-stack; alias gdb-tmux-sv-frame; alias gdb-sv-stack; alias gdb-sv-frame' 2>/dev/null || true)
echo "$AL" | grep -q 'stackview-pane.sh stack' \
    && echo "$AL" | grep -q 'stackview-pane.sh frame' \
    && ok "gdb-tmux-sv-* + gdb-sv-* expand in interactive bash" \
    || bad "aliases do not load (source ~/.bashrc?)"

echo
echo "  stackview: $PASS passed, $FAIL failed"
echo "  usage (ONE pane per view):"
echo "    gdb:    (gdb) pwn   (or init-stackview) -- every stop updates ALL view files"
echo "    tmux:   gdb-tmux-sv-stack / gdb-tmux-sv-frame   # split a pane with the view"
echo "    plain:  gdb-sv-stack / gdb-sv-frame            # run the pane HERE, no tmux (Ctrl-C quits)"
echo "    raw:    tmux split-window -h 'bash ~/stackview/stackview-pane.sh stack'"
echo "    gdb:    stackview off | stackview on | stackview default | stackview <view...>"
[ "$FAIL" -eq 0 ] && exit 0 || exit 1