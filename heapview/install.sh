#!/usr/bin/env bash
# heapview/install.sh -- dedicated auto-refresh heap pane (separate tmux window)
#
# 1. apt: tmux
# 2. files: ~/heapview/heapview.py + ~/heapview/heapview-pane.sh
# 3. ~/.gdbinit: `init-heapview` define (own marker block)
# 4. ~/.bashrc marker block: source /etc/bash_aliases.d/.bashrc_alias_gdb
#    (aliases file lives in /etc/bash_aliases.d/, copied from this folder,
#    executable; Debian bash does NOT source that dir by default -> the
#    ~/.bashrc block sources it explicitly)
#
# In gdb:   `init-heapview`  -> on EVERY stop (break/step/signal) EVERY view is
#           written to its OWN file:  /tmp/gdb-view-<view>.txt
#           (commands -> file per command; builtin '@arena' -> gdb-view-arena.txt)
# In tmux:  ONE pane PER view:  tmux split-window -h 'bash ~/heapview/heapview-pane.sh heapinfo'
#                                   tmux split-window -h 'bash ~/heapview/heapview-pane.sh arena'
#
# default views: heapinfo + @arena   (gdb: `heapview` to list, `heapview <views...>` to set)
#
# gdb TUI cannot do custom windows (tui new-layout -> "Unknown window"),
# hence the stop-hook -> file -> pane architecture.
set -euo pipefail

HOME_DIR="${HOME:?}"
SRC="$(cd "$(dirname "$0")" && pwd)"
DEST="$HOME_DIR/heapview"
PASS=0; FAIL=0
log()  { printf '\n\033[1;36m[heapview]\033[0m %s\n' "$*"; }
ok()   { printf '  \033[1;32mPASS\033[0m  %s\n' "$*"; PASS=$((PASS+1)); }
bad()  { printf '  \033[1;31mFAIL\033[0m  %s\n' "$*"; FAIL=$((FAIL+1)); }
[ "$(id -u)" -eq 0 ] && SUDO="" || SUDO="sudo"

# --- shared helper: idempotent marker block in ~/.gdbinit --------------------
gdbinit_block() { # $1=name, content on stdin
    local name="$1" init="$HOME_DIR/.gdbinit"
    touch "$init"
    sed -i "/^# >>> $name >>>$/,/^# <<< $name <<</d" "$init" 2>/dev/null || true
    printf '# >>> %s >>>\n' "$name" >> "$init"
    cat >> "$init"
    printf '# <<< %s <<<\n\n' "$name" >> "$init"
}

# --- shared helper: idempotent marker block in ~/.bashrc ----------------------
bashrc_block() { # $1=name, content on stdin
    local name="$1" file="$HOME_DIR/.bashrc"
    touch "$file"
    sed -i "/^# >>> $name >>>$/,/^# <<< $name <<</d" "$file" 2>/dev/null || true
    printf '# >>> %s >>>\n' "$name" >> "$file"
    cat >> "$file"
    printf '# <<< %s <<<\n\n' "$name" >> "$file"
}

log "1/4  apt (tmux)"
export DEBIAN_FRONTEND=noninteractive
if $SUDO apt-get install -y tmux >/dev/null 2>&1; then ok "tmux present"; else bad "apt install tmux failed"; fi

log "2/4  files -> ~/heapview"
mkdir -p "$DEST"
cp "$SRC/heapview.py"       "$DEST/heapview.py"
cp "$SRC/heapview-pane.sh"  "$DEST/heapview-pane.sh"
chmod +x "$DEST/heapview-pane.sh"
[ -f "$DEST/heapview.py" ] && [ -f "$DEST/heapview-pane.sh" ] \
    && ok "heapview.py + heapview-pane.sh installed" || bad "files missing after copy"

log "3/4  ~/.gdbinit (init-heapview define)"
# migration: legacy file (old install_gdb.bash, no marker blocks) -> backup + reset;
# custom/unknown files are kept, only our block is appended
GDBINIT="$HOME_DIR/.gdbinit"
if [ -f "$GDBINIT" ] && ! grep -q '^# >>>' "$GDBINIT"; then
    [ -f "$HOME_DIR/.gdbinit.legacy" ] || cp "$GDBINIT" "$HOME_DIR/.gdbinit.legacy"
    grep -q '^# ~/.gdbinit -- generated by install_gdb.bash' "$GDBINIT" \
        && : > "$GDBINIT" || true   # || true: custom files (no signature) must not abort
fi
{
    echo "define init-heapview"
    echo "source ~/heapview/heapview.py"
    echo "end"
    echo "document init-heapview"
    echo "Auto heap views: every stop writes EACH view to /tmp/gdb-view-<view>.txt (one pane per view: bash ~/heapview/heapview-pane.sh <view>)"
    echo "end"
} | gdbinit_block heapview
grep -q 'source ~/heapview/heapview.py' "$HOME_DIR/.gdbinit" \
    && ok "init-heapview wired into ~/.gdbinit" || bad "gdbinit block missing"

# --- 4/4: aliases file -> /etc/bash_aliases.d/ + ~/.bashrc source block ---------
log "4/4  aliases file -> /etc/bash_aliases.d/ + ~/.bashrc source block"
ALIAS_DEST=/etc/bash_aliases.d/.bashrc_alias_gdb
$SUDO mkdir -p /etc/bash_aliases.d
if $SUDO cp "$SRC/.bashrc_alias_gdb" "$ALIAS_DEST" \
   && $SUDO chmod +x "$ALIAS_DEST"; then
    ok "$ALIAS_DEST installed (executable)"
else
    bad "could not copy/chmod $ALIAS_DEST (need $SUDO?)"
fi
[ -x "$ALIAS_DEST" ] && ok "aliases file is executable" || bad "aliases file not executable"
{
    echo "# heap-tools: source the gdb view-pane aliases (gdb-tmux-hv-*)"
    echo "[ -f $ALIAS_DEST ] && . $ALIAS_DEST"
} | bashrc_block heap-tools
grep -q "\. $ALIAS_DEST" "$HOME_DIR/.bashrc" \
    && ok "~/.bashrc sources $ALIAS_DEST" || bad "source block missing from .bashrc"

log "verify"
cat > /tmp/heapview-check.gdb <<'EOF'
set pagination off
init-heapview
starti
quit
EOF
rm -f /tmp/gdb-view-*.txt
timeout 120 gdb -q -batch -x /tmp/heapview-check.gdb /bin/true >/dev/null 2>&1 || true
grep -q 'top:' /tmp/gdb-view-heapinfo.txt 2>/dev/null \
    && ok "view file gdb-view-heapinfo.txt written on stop" \
    || { grep -q 'stop:' /tmp/gdb-view-heapinfo.txt 2>/dev/null \
         && ok "view file gdb-view-heapinfo.txt written (heap not yet created -> no top: yet)" \
         || bad "heapinfo view file not written"; }
grep -q 'arena' /tmp/gdb-view-arena.txt 2>/dev/null \
    && ok "view file gdb-view-arena.txt written on stop" \
    || bad "arena view file not written"
rm -f /tmp/heapview-check.gdb /tmp/gdb-view-*.txt /tmp/gdb-view-req/*

# panes self-register: a live pane touches its request every second; emulate
# that with a background toucher during the gdb run (a single touch would
# expire before gdb's startup finishes)
mkdir -p /tmp/gdb-view-req
( for i in $(seq 1 60); do touch /tmp/gdb-view-req/parseheap; sleep 1; done ) &
TOUCHER=$!
cat > /tmp/gdb-check.c <<'CEOF'
#include <stdlib.h>
int main(void) {
    void *a = malloc(0x20);
    void *b = malloc(0x100);
    void *c = malloc(0x20);
    free(b);
    free(a);
    free(c);
    return 0;
}
CEOF
cat > /tmp/heapview-check.gdb <<'EOF2'
set pagination off
init-pwngdb
starti
break gdb-check.c:8
continue
quit
EOF2
gcc -g -O0 -o /tmp/gdb-check /tmp/gdb-check.c 2>/dev/null
timeout 150 gdb -q -batch -x /tmp/heapview-check.gdb /tmp/gdb-check >/dev/null 2>&1 || true
kill $TOUCHER 2>/dev/null || true
wait $TOUCHER 2>/dev/null || true
# heapinfo must be FRESH here (not the load-time placeholder) -- catches the
# shared-python-namespace bug where a plugin sourced later (stackview!) clobbers
# this hook's globals and it stops writing its own view files
grep -q 'top:' /tmp/gdb-view-heapinfo.txt 2>/dev/null \
    && ok "heapinfo fresh under init-pwngdb (hook not clobbered)" \
    || bad "heapinfo is stale (placeholder) -- hook globals clobbered?"
grep -q 'Used' /tmp/gdb-view-parseheap.txt 2>/dev/null \
    && ok "pane self-registration: request parseheap -> view written" \
    || bad "requested view (parseheap) not written"
rm -f /tmp/heapview-check.gdb /tmp/gdb-view-*.txt /tmp/gdb-check /tmp/gdb-check.c
rm -rf /tmp/gdb-view-req

# aliases load in an interactive shell (chain: .bashrc -> source /etc file)
AL=$(bash -ic 'alias gdb-tmux-hv-heapinfo; alias gdb-tmux-hv-arena; alias gdb-hv-heapinfo; alias gdb-hv-arena' 2>/dev/null || true)
echo "$AL" | grep -q 'heapview-pane.sh heapinfo' \
    && echo "$AL" | grep -q 'heapview-pane.sh arena' \
    && ok "gdb-tmux-hv-* + gdb-hv-* expand in interactive bash" \
    || bad "aliases do not load (source ~/.bashrc?)"

echo
echo "  heapview: $PASS passed, $FAIL failed"
echo "  usage (ONE pane per view):"
echo "    gdb:    (gdb) pwn   (or init-pwngdb / init-heapview) -- every stop updates ALL view files"
echo "    tmux:   gdb-tmux-hv-heapinfo / gdb-tmux-hv-arena     # split a pane with the view"
echo "    plain:  gdb-hv-heapinfo / gdb-hv-arena              # run the pane HERE, no tmux (Ctrl-C quits)"
echo "    raw:    tmux split-window -h 'bash ~/heapview/heapview-pane.sh heapinfo'"
echo "    gdb:    heapview off | heapview on | heapview default | heapview <view...>"
[ "$FAIL" -eq 0 ] && exit 0 || exit 1